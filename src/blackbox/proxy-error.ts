/**
 * 代理错误页识别：请求根本没到目标，回来的却是代理自己的报错页面。
 *
 * 为什么必须单独识别（2026-11-06 wxmc.topsec.com.cn 实测）：
 *
 *   容器出网走 Burp（`HTTP(S)_PROXY=http://host.docker.internal:8080`）。目标不可达时，
 *   Burp 不返回连接失败，而是**用它自己的错误页顶替响应，状态码仍是 200**。于是：
 *
 *     - 系统把它当"目标返回 200"，7 条不同路径全是 1381B 的同一个页面；
 *     - `detectAnomaly` 判定"全站同长度响应"，派发 Host 头注入 / 开放重定向 / 子域接管
 *       三条任务——**假信号直接改写了整场的作战计划**；
 *     - 模型在 `analysis` 里自己发现了 `<title>Burp Suite Professional</title>`，
 *       但那已经是烧掉半场预算之后；
 *     - `browser.open` 走同一个代理，Chromium 永远等不到响应，一个工具吃掉 5 分钟。
 *
 * 判据只认代理产品的**专有标记**，不用"200 但正文很短""同长度"这类形状启发式——
 * 形状启发式正是被污染的那套逻辑。命中即判传输失败（ok:false），让它落成 tool-error，
 * 不进入 `recordAnomaly`、不当作目标响应证据。
 */

export type ProxyErrorHit = {
  /** 代理产品名，写进 summary 让人一眼知道是谁拦的。 */
  vendor: "burp" | "mitmproxy" | "squid" | "tinyproxy" | "charles" | "fiddler";
  /** 命中的那段原文，便于事后核对。 */
  marker: string;
  /** 代理在错误页里给出的原因（Burp 会写 "Failed to connect" 之类），有就带上。 */
  detail?: string;
};

type Marker = { vendor: ProxyErrorHit["vendor"]; pattern: RegExp };

/**
 * 只收"这个页面只可能来自代理"的标记。宁可漏判（下一次还会撞上），
 * 不可误判（把目标真实页面当成代理错误，会凭空丢掉一条有效证据）。
 */
const MARKERS: Marker[] = [
  // Burp Suite Community/Professional 的错误页，标题固定。
  { vendor: "burp", pattern: /<title>\s*Burp Suite (?:Professional|Community Edition)\s*<\/title>/i },
  { vendor: "burp", pattern: /Burp Proxy error:/i },
  // mitmproxy 的 error page。
  { vendor: "mitmproxy", pattern: /<title>\s*mitmproxy\s*<\/title>/i },
  // Squid 的经典错误页。
  { vendor: "squid", pattern: /<title>\s*ERROR:\s*The requested URL could not be retrieved\s*<\/title>/i },
  // tinyproxy。
  { vendor: "tinyproxy", pattern: /Generated by <a href="https:\/\/tinyproxy\.github\.io\/">tinyproxy<\/a>/i },
  // Charles。
  { vendor: "charles", pattern: /<title>\s*Charles Proxy\s*<\/title>/i },
  // Fiddler。
  { vendor: "fiddler", pattern: /<title>\s*Fiddler\s*<\/title>[\s\S]{0,400}(?:Fiddler|proxy)/i },
];

const TEXT_LIMIT = 64 * 1024;

export function proxyErrorPage(input: {
  status?: number;
  headers?: Record<string, string> | Array<{ name: string; value: string }>;
  body?: string;
}): ProxyErrorHit | undefined {
  const body = String(input.body || "");
  if (!body) return undefined;
  // 错误页一定是 HTML；不先按内容类型收窄，纯文本正文里的巧合字样会被误判。
  const head = body.slice(0, TEXT_LIMIT);
  if (!/<html|<!doctype|<title/i.test(head)) return undefined;
  for (const marker of MARKERS) {
    const match = marker.pattern.exec(head);
    if (!match) continue;
    return { vendor: marker.vendor, marker: match[0].slice(0, 120), detail: reasonOf(head) };
  }
  return undefined;
}

/**
 * 从错误页里抠出代理自己写的原因。各产品的措辞不一样，抓不到就返回 undefined，
 * 不硬凑——summary 里缺这一句不影响判定。
 */
function reasonOf(html: string): string | undefined {
  const text = html.replace(/<script[\s\S]*?<\/script>/gi, " ").replace(/<[^>]+>/g, " ").replace(/\s+/g, " ");
  const patterns = [
    /Failed to (?:connect|resolve)[^.]{0,120}\./i,
    /Could not (?:connect|resolve)[^.]{0,120}\./i,
    /(?:Connection|Host) (?:refused|timed out|not found)[^.]{0,80}/i,
    /The requested URL could not be retrieved[^.]{0,0}/i,
    /unable to (?:connect|resolve)[^.]{0,120}\./i,
  ];
  for (const pattern of patterns) {
    const match = pattern.exec(text);
    if (match) return match[0].trim().slice(0, 200);
  }
  return undefined;
}

/** 归一化成一个给人看的一句结论，summary 直接用它开头。 */
export function proxyErrorSummary(hit: ProxyErrorHit, input: { method?: string; url?: string; status?: number; bytes?: number }): string {
  const where = `${input.method || "GET"} ${input.url || ""}`.trim();
  return `${where} 没有到达目标：${hit.vendor} 代理返回了它自己的错误页（HTTP ${input.status ?? "?"}，${input.bytes ?? 0}B${hit.detail ? `，代理原因：${hit.detail}` : ""}）。`
    + "这不是目标的响应，不能当状态码或正文证据用。"
    + "处理：确认该主机是否可达（换 DNS/直连/换代理），或换一个能连上的目标；重复发同样的请求只会拿到同一个错误页。";
}
