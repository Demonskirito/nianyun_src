import { describe, expect, it } from "vitest";
import { proxyErrorPage, proxyErrorSummary } from "../src/blackbox/proxy-error.js";

/**
 * 这批用例钉住 2026-11-06 那个真实事故：目标不可达时，代理用它自己的错误页顶替响应，
 * 状态码仍是 200。系统把它当"目标返回 200"，于是 7 条不同路径都是 1381B 同一个页面，
 * `uniform_body` 异常被触发，整场的作战计划被一个假信号改写。
 */
describe("代理错误页识别", () => {
  const BURP = `<html><head><title>Burp Suite Professional</title>
<style type="text/css">body { background: #dedede; }</style></head>
<body><div id="container"><h1>Failed to connect to the target server.</h1></div></body></html>`;

  it("Burp 错误页：200 也照判（这是本次事故的原始形态）", () => {
    const hit = proxyErrorPage({ status: 200, body: BURP });
    expect(hit?.vendor).toBe("burp");
    expect(hit?.detail).toContain("Failed to connect");
  });

  it("Burp 的 Proxy error 文案也能认（不带 title 的变体）", () => {
    expect(proxyErrorPage({ status: 502, body: "<html><body>Burp Proxy error: connection refused</body></html>" })?.vendor).toBe("burp");
  });

  it("mitmproxy / squid / tinyproxy 各自的产品标记", () => {
    expect(proxyErrorPage({ status: 200, body: "<html><title>mitmproxy</title></html>" })?.vendor).toBe("mitmproxy");
    expect(proxyErrorPage({
      status: 200,
      body: "<html><title>ERROR: The requested URL could not be retrieved</title></html>",
    })?.vendor).toBe("squid");
    expect(proxyErrorPage({
      status: 200,
      body: '<html><body>Generated by <a href="https://tinyproxy.github.io/">tinyproxy</a></body></html>',
    })?.vendor).toBe("tinyproxy");
  });

  it("目标自己的正常页面不能被误判——误判会凭空丢掉一条有效证据", () => {
    expect(proxyErrorPage({
      status: 200,
      body: "<html><head><title>万小智 3.0 - 阿里云旗下AI建站与经营平台</title></head><body><div id=\"root\"></div></body></html>",
    })).toBeUndefined();
  });

  it("非 HTML 正文里的巧合字样不算（先按结构收窄，再看标记）", () => {
    expect(proxyErrorPage({ status: 200, body: "Burp Suite Professional is mentioned in this plain text log" })).toBeUndefined();
    expect(proxyErrorPage({ status: 200, body: "" })).toBeUndefined();
  });

  it("summary 要说清三件事：没到目标、不是证据、该怎么办", () => {
    const hit = proxyErrorPage({ status: 200, body: BURP })!;
    const text = proxyErrorSummary(hit, { method: "GET", url: "https://wxmc.topsec.com.cn/", status: 200, bytes: 1381 });
    expect(text).toContain("没有到达目标");
    expect(text).toContain("burp");
    expect(text).toContain("1381B");
    expect(text).toContain("不是目标的响应");
    expect(text).toContain("换");
  });
});
